void SimulatorApp::investigateAndRespond() {
    if (m_incidents.empty()) {
        std::cout << "\n[NOTICE] No security incidents available to investigate.\n";
        return;
    }

    viewActiveIncidents();

    std::cout << "Enter Incident ID to investigate: ";
    int targetIncId;
    if (!(std::cin >> targetIncId)) {
        std::cin.clear();
        std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
        std::cout << "[ERROR] Invalid ID input.\n";
        return;
    }

    SecurityIncident* inc = findIncidentById(targetIncId);
    if (inc == nullptr) {
        std::cout << "[ERROR] Incident ID #" << targetIncId << " does not exist.\n";
        return;
    }

    // Polymorphic Call: investigate()
    inc->investigate();

    // Polymorphic Response Menu
    inc->printResponseOptions();
    int choice = getValidatedIntInput(1, 4);

    // Polymorphic Call: applyResponse()
    bool applied = inc->applyResponse(choice);
    if (applied) {
        std::cout << "[STATUS] Incident #" << inc->getId()
                  << " updated. Current state: [" << inc->getStatusString() << "]\n";
    }
}

void SimulatorApp::generateRandomIncident() {
    if (m_devices.empty()) {
        std::cout << "[ERROR] No devices available to target.\n";
        return;
    }

    // Seed modern standard C++ random engine
    std::random_device rd;
    std::mt19937 gen(rd());

    std::uniform_int_distribution<size_t> deviceDist(0, m_devices.size() - 1);
    std::uniform_int_distribution<int> typeDist(0, 1); // 0 = Malware, 1 = DDoS

    size_t targetIndex = deviceDist(gen);
    NetworkDevice* target = m_devices[targetIndex].get();

    int incType = typeDist(gen);
    std::string timestamp = getCurrentTimestamp();

    if (incType == 0) {
        // Malware Incident
        target->setStatus(DeviceStatus::COMPROMISED);
        std::uniform_int_distribution<int> malwareVariantDist(0, 2);
        int variant = malwareVariantDist(gen);

        std::string title;
        std::string sig;
        std::string proc;
        IncidentSeverity sev = IncidentSeverity::HIGH;

        if (variant == 0) {
            title = "Ransomware Lockdown Attempt";
            sig = "WannaCryptor.Gen4.Ransom";
            proc = "taskhostw_enc.exe";
            sev = IncidentSeverity::CRITICAL;
        } else if (variant == 1) {
            title = "Credential Harvester Spyware";
            sig = "Infostealer.RedLine.v3";
            proc = "rundll32_hook.exe";
            sev = IncidentSeverity::HIGH;
        } else {
            title = "Unauthorized Cryptomining Daemon";
            sig = "CoinMiner.XMRig.Payload";
            proc = "system_miner_svc";
            sev = IncidentSeverity::MEDIUM;
        }

        auto incident = std::make_unique<MalwareIncident>(
            m_nextIncidentId++, title, sev, target, timestamp, sig, proc);
        incident->appendLog("Endpoint telemetry detected malicious signature match: " + sig);
        m_incidents.push_back(std::move(incident));

        std::cout << "\n>>> [SECURITY ALERT TRIGGERED] <<<\n"
                  << "  Type    : Malware Outbreak\n"
                  << "  Target  : " << target->getHostname() << " (" << target->getIpAddress() << ")\n"
                  << "  Threat  : " << title << "\n"
                  << "  Device status set to: [" << target->getStatusString() << "]\n";
    } else {
        // DDoS Incident
        target->setStatus(DeviceStatus::UNDER_ATTACK);
        std::uniform_real_distribution<double> bandwidthDist(35.0, 180.0);
        double volume = bandwidthDist(gen);

        std::uniform_int_distribution<int> ddosTypeDist(0, 2);
        int ddosType = ddosTypeDist(gen);

        std::string title;
        std::string vector;
        IncidentSeverity sev = (volume > 100.0) ? IncidentSeverity::CRITICAL : IncidentSeverity::HIGH;

        if (ddosType == 0) {
            title = "Volumetric NTP Amplification Assault";
            vector = "UDP NTP Monlist Reflection Amplification";
        } else if (ddosType == 1) {
            title = "Distributed SYN Flood Attack";
            vector = "TCP SYN Half-Open Socket Exhaustion";
        } else {
            title = "Layer 7 HTTP POST Flood";
            vector = "HTTPS Slowloris / Application Queue Starvation";
        }

        auto incident = std::make_unique<DDoSIncident>(
            m_nextIncidentId++, title, sev, target, timestamp, vector, volume);
        incident->appendLog("Border gateway detected sudden volumetric influx exceeding SLA bandwidth.");
        m_incidents.push_back(std::move(incident));

        std::cout << "\n>>> [SECURITY ALERT TRIGGERED] <<<\n"
                  << "  Type    : DDoS Flooding Attack\n"
                  << "  Target  : " << target->getHostname() << " (" << target->getIpAddress() << ")\n"
                  << "  Vector  : " << vector << "\n"
                  << "  Volume  : " << std::fixed << std::setprecision(1) << volume << " Gbps\n"
                  << "  Device status set to: [" << target->getStatusString() << "]\n";
    }
}

void SimulatorApp::saveIncidentReportToFile() const {
    const std::string filename = "cyber_incident_report.txt";
    std::ofstream outFile(filename, std::ios::out | std::ios::trunc);

    if (!outFile.is_open()) {
        std::cout << "[ERROR] Unable to create report file '" << filename << "'. Check disk permissions.\n";
        return;
    }

    std::string timestamp = getCurrentTimestamp();

    outFile << "========================================================================================\n"
            << "                      CYBER INCIDENT RESPONSE SIMULATOR - AUDIT REPORT                  \n"
            << "========================================================================================\n"
            << "Generated At: " << timestamp << "\n"
            << "Total Monitored Devices : " << m_devices.size() << "\n"
            << "Total Security Incidents: " << m_incidents.size() << "\n\n";

    // Summary Count
    int onlineCount = 0;
    int compromisedCount = 0;
    int isolatedCount = 0;
    int underAttackCount = 0;

    for (const auto& dev : m_devices) {
        switch (dev->getStatus()) {
            case DeviceStatus::ONLINE:       onlineCount++; break;
            case DeviceStatus::COMPROMISED: compromisedCount++; break;
            case DeviceStatus::ISOLATED:     isolatedCount++; break;
            case DeviceStatus::UNDER_ATTACK: underAttackCount++; break;
            default: break;
        }
    }

    int activeIncidentsCount = 0;
    int resolvedIncidentsCount = 0;

    for (const auto& inc : m_incidents) {
        if (inc->getStatus() == IncidentStatus::RESOLVED) {
            resolvedIncidentsCount++;
        } else {
            activeIncidentsCount++;
        }
    }

    outFile << "--- SECURITY POSTURE EXECUTIVE SUMMARY ---\n"
            << "  Healthy (ONLINE)      : " << onlineCount << "\n"
            << "  COMPROMISED Devices   : " << compromisedCount << "\n"
            << "  ISOLATED Devices      : " << isolatedCount << "\n"
            << "  UNDER ATTACK Devices  : " << underAttackCount << "\n"
            << "  Active Incidents      : " << activeIncidentsCount << "\n"
            << "  Resolved Incidents    : " << resolvedIncidentsCount << "\n\n";

    outFile << "--- NETWORK INFRASTRUCTURE INVENTORY ---\n"
            << std::left
            << std::setw(6)  << "ID"
            << std::setw(22) << "Hostname"
            << std::setw(18) << "IP Address"
            << std::setw(42) << "Device Role"
            << std::setw(16) << "Status"
            << "\n"
            << "--------------------------------------------------------------------------------------------------------\n";

    for (const auto& dev : m_devices) {
        outFile << std::left
                << std::setw(6)  << dev->getId()
                << std::setw(22) << dev->getHostname()
                << std::setw(18) << dev->getIpAddress()
                << std::setw(42) << dev->getDeviceRole()
                << std::setw(16) << dev->getStatusString()
                << "\n";
    }

    outFile << "\n--- DETAILED INCIDENT AUDIT LOGS ---\n\n";
    if (m_incidents.empty()) {
        outFile << "No security incidents recorded during simulation session.\n";
    } else {
        for (const auto& inc : m_incidents) {
            outFile << inc->getDetailedReport() << "\n";
        }
    }

    outFile << "========================================================================================\n"
            << "                              END OF INCIDENT REPORT                                    \n"
            << "========================================================================================\n";

    outFile.close();

    std::cout << "\n[SUCCESS] Incident report successfully generated and saved to: "
              << filename << "\n";
}

void SimulatorApp::run() {
    bool running = true;

    while (running) {
        std::cout << "\n===========================================================\n"
                  << "        CYBER INCIDENT RESPONSE SIMULATOR (C++17)          \n"
                  << "===========================================================\n"
                  << " [1] View Network Status\n"
                  << " [2] View Active Incidents\n"
                  << " [3] Investigate & Respond to Incident\n"
                  << " [4] Generate Random Incident\n"
                  << " [5] Save Incident Report to File (.txt)\n"
                  << " [6] Exit\n"
                  << "===========================================================\n";

        int choice = getValidatedIntInput(1, 6);

        switch (choice) {
            case 1:
                viewNetworkStatus();
                break;
            case 2:
                viewActiveIncidents();
                break;
            case 3:
                investigateAndRespond();
                break;
            case 4:
                generateRandomIncident();
                break;
            case 5:
                saveIncidentReportToFile();
                break;
            case 6:
                std::cout << "\nTerminating Cyber Incident Response Simulator. Stay safe!\n";
                running = false;
                break;
            default:
                break;
        }
    }
}
