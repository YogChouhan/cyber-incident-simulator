    m_devices.push_back(make_unique<Firewall>(
        m_nextDeviceId++, "fw-edge-perimeter", "192.168.1.1", "Strict Ingress Drop & DPI Filtering", 12480, DeviceStatus::ONLINE));

    // Seed one initial incident on ws-fin-04
    NetworkDevice* target = findDeviceById(3);
