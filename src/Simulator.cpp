// Returns the formatted local time using Windows localtime_s
string SimulatorApp::getCurrentTimestamp() const {
    time_t timeNow = time(nullptr);
    tm localTm;
    if (localtime_s(&localTm, &timeNow) == 0) {
        char buffer[64];
        strftime(buffer, sizeof(buffer), "%Y-%m-%d %H:%M:%S", &localTm);
        return string(buffer);
    }
    return "UNKNOWN-TIME";
}

// Searches the device list and returns a non-owning pointer to the matching device
NetworkDevice* SimulatorApp::findDeviceById(int id) const {
    for (const auto& dev : m_devices) {
        if (dev->getId() == id) {
            return dev.get();
        }
    }
    return nullptr;
}

// Searches the incident list and returns a non-owning pointer to the matching incident
SecurityIncident* SimulatorApp::findIncidentById(int id) const {
    for (const auto& inc : m_incidents) {
        if (inc->getId() == id) {
            return inc.get();
        }
    }
    return nullptr;
}

// Reads an entire line, parses an integer safely with stoi, and checks range
int SimulatorApp::getValidatedIntInput(int minVal, int maxVal, const string& prompt) const {
    string line;
    while (true) {
        if (prompt.empty()) {
            cout << "Enter choice (" << minVal << " - " << maxVal << "): ";
        } else {
            cout << prompt << " (" << minVal << " - " << maxVal << "): ";
        }

        if (!getline(cin, line)) {
            if (cin.eof()) {
                cout << "\n[NOTICE] End of input reached. Exiting cleanly.\n";
                throw runtime_error("Input closed");
            }
            cout << "[ERROR] Input read error occurred.\n";
            continue;
        }

        // Trim leading and trailing whitespace
        size_t start = line.find_first_not_of(" \t\r\n");
        if (start == string::npos) {
            cout << "[ERROR] Input cannot be empty. Please enter a valid number.\n";
            continue;
        }
        size_t end = line.find_last_not_of(" \t\r\n");
        string trimmed = line.substr(start, end - start + 1);

        try {
            size_t idx = 0;
            int inputVal = stoi(trimmed, &idx);

            // Reject leftover characters (e.g., "12abc")
            if (idx != trimmed.length()) {
                cout << "[ERROR] Invalid characters detected. Please enter digits only.\n";
                continue;
            }

            if (inputVal >= minVal && inputVal <= maxVal) {
                return inputVal;
            }
            cout << "[ERROR] Selection out of range. Please enter a value between "
                 << minVal << " and " << maxVal << ".\n";
        } catch (const invalid_argument&) {
            cout << "[ERROR] Invalid input. Please enter a numeric choice.\n";
        } catch (const out_of_range&) {
            cout << "[ERROR] Number is out of allowable range.\n";
        }
    }
}

// Displays all devices in the network in a table and offers optional deep diagnostics
void SimulatorApp::viewNetworkStatus() const {
    cout << "\n========================================================================================================\n"
         << "                                     CURRENT NETWORK INFRASTRUCTURE                                     \n"
         << "========================================================================================================\n"
         << left
         << setw(6)  << "ID"
         << setw(22) << "Hostname"
         << setw(18) << "IP Address"
         << setw(42) << "Role"
         << setw(16) << "Status"
         << "\n"
         << "--------------------------------------------------------------------------------------------------------\n";

    for (const auto& dev : m_devices) {
        cout << left
             << setw(6)  << dev->getId()
             << setw(22) << dev->getHostname()
             << setw(18) << dev->getIpAddress()
             << setw(42) << dev->getDeviceRole()
             << setw(16) << dev->getStatusString()
             << "\n";
    }
    cout << "========================================================================================================\n\n";

    int inspectChoice = getValidatedIntInput(0, 1, "Inspect deep diagnostics of a specific device? (1: Yes, 0: No)");
    if (inspectChoice == 1) {
        int devId = getValidatedIntInput(1, static_cast<int>(m_devices.size()), "Enter Device ID to inspect");
        NetworkDevice* dev = findDeviceById(devId);
        if (dev != nullptr) {
            cout << "\n------------------ DEVICE DEEP PROFILE ------------------\n";
            dev->displayInfo();
            cout << "\n------------------ DIAGNOSTIC TRACE --------------------\n";
            dev->performDiagnostics();
            cout << "---------------------------------------------------------\n";
        } else {
            cout << "[ERROR] Device ID not found.\n";
        }
    }
}

