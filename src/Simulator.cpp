SimulatorApp::SimulatorApp()
    : m_nextIncidentId(101),
      m_nextDeviceId(1) {
    initializeDefaultNetwork();
}

void SimulatorApp::initializeDefaultNetwork() {
    // Populate realistic enterprise network devices
    m_devices.push_back(std::make_unique<Server>(
        m_nextDeviceId++, "srv-prod-db01", "10.0.1.10", "PostgreSQL Enterprise Cluster", 145, DeviceStatus::ONLINE));

    m_devices.push_back(std::make_unique<Server>(
        m_nextDeviceId++, "srv-web-gateway", "10.0.1.20", "Nginx Reverse Proxy & API Gateway", 420, DeviceStatus::ONLINE));

    m_devices.push_back(std::make_unique<Workstation>(
        m_nextDeviceId++, "ws-fin-04", "10.0.2.14", "Samantha Reed (Finance)", "Windows 11 Pro Enterprise", DeviceStatus::ONLINE));

    m_devices.push_back(std::make_unique<Workstation>(
        m_nextDeviceId++, "ws-dev-09", "10.0.2.35", "Alex Chen (DevOps)", "Ubuntu Linux 24.04 LTS", DeviceStatus::ONLINE));

    m_devices.push_back(std::make_unique<Firewall>(
        m_nextDeviceId++, "fw-edge-perimeter", "192.168.1.1", "Strict Ingress Drop & DPI Filtering", 12480, DeviceStatus::ONLINE));

    // Seed one initial active incident so the user has immediate context
    NetworkDevice* target = findDeviceById(3); // ws-fin-04
    if (target != nullptr) {
        target->setStatus(DeviceStatus::COMPROMISED);
        auto initialIncident = std::make_unique<MalwareIncident>(
            m_nextIncidentId++,
            "Suspicious Phishing Dropper Infection",
            IncidentSeverity::HIGH,
            target,
            getCurrentTimestamp(),
            "Trojan.Win32.CobaltStrike.Stager",
            "invoice_december.pdf.exe"
        );
        initialIncident->appendLog("Initial alert generated by Host IDS heuristics.");
        m_incidents.push_back(std::move(initialIncident));
    }
}

std::string SimulatorApp::getCurrentTimestamp() const {
    std::time_t timeNow = std::time(nullptr);
    std::tm* localTm = std::localtime(&timeNow);
    char buffer[64];
    if (localTm != nullptr) {
        std::strftime(buffer, sizeof(buffer), "%Y-%m-%d %H:%M:%S", localTm);
    } else {
        return "2026-10-14 12:00:00";
    }
    return std::string(buffer);
}

NetworkDevice* SimulatorApp::findDeviceById(int id) const {
    for (const auto& dev : m_devices) {
        if (dev->getId() == id) {
            return dev.get();
        }
    }
    return nullptr;
}

SecurityIncident* SimulatorApp::findIncidentById(int id) const {
    for (const auto& inc : m_incidents) {
        if (inc->getId() == id) {
            return inc.get();
        }
    }
    return nullptr;
}

int SimulatorApp::getValidatedIntInput(int minVal, int maxVal) const {
    int inputVal;
    while (true) {
        std::cout << "Enter choice (" << minVal << " - " << maxVal << "): ";
        if (std::cin >> inputVal) {
            if (inputVal >= minVal && inputVal <= maxVal) {
                return inputVal;
            }
            std::cout << "[ERROR] Selection out of range. Please enter a value between "
                      << minVal << " and " << maxVal << ".\n";
        } else {
            std::cout << "[ERROR] Invalid input. Please enter a numeric choice.\n";
            std::cin.clear();
            std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
        }
    }
}

